package com.mycompany.chatapplication.utils;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.*;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

/** Small JDBC repository for the existing group-chat features. */
public final class DBManager {
    private static final String DEFAULT_URL = "jdbc:h2:file:./chat-data/mzansi;DB_CLOSE_ON_EXIT=FALSE";
    private static volatile boolean ready = false;
    private DBManager() {}

    public static final class ChatMessage {
        public final long id;
        public final String sender;
        public final String content;
        public final String timestamp;
        public ChatMessage(long id, String sender, String content, String timestamp) {
            this.id = id;
            this.sender = sender;
            this.content = content;
            this.timestamp = timestamp;
        }
    }

    private static Connection connect() throws SQLException {
        String url = System.getenv("DB_URL");
        if (url == null || url.isBlank()) {
            try { Files.createDirectories(Path.of("chat-data")); }
            catch (Exception ex) { throw new SQLException("Unable to create local chat-data directory", ex); }
            url = DEFAULT_URL;
        }
        String user = System.getenv("DB_USER");
        String pass = System.getenv("DB_PASSWORD");
        return DriverManager.getConnection(url, user == null ? "sa" : user, pass == null ? "" : pass);
    }

    public static synchronized void initialize() throws SQLException {
        if (ready) return;
        try (Connection conn = connect(); Statement st = conn.createStatement()) {
            st.execute("CREATE TABLE IF NOT EXISTS users (" +
                    "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                    "username VARCHAR(24) NOT NULL UNIQUE," +
                    "password_hash VARCHAR(300) NOT NULL)");
            st.execute("CREATE TABLE IF NOT EXISTS messages (" +
                    "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                    "user_id BIGINT NOT NULL REFERENCES users(id)," +
                    "content VARCHAR(1000) NOT NULL," +
                    "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)");
            ready = true;
        }
    }

    public static boolean createUser(String username, String passwordHash) throws SQLException {
        initialize();
        try (Connection conn = connect();
             PreparedStatement st = conn.prepareStatement("INSERT INTO users(username,password_hash) VALUES (?,?)")) {
            st.setString(1, username);
            st.setString(2, passwordHash);
            st.executeUpdate();
            return true;
        } catch (SQLException ex) {
            if ("23505".equals(ex.getSQLState())) return false; // Duplicate username in PostgreSQL and H2
            throw ex;
        }
    }

    public static String passwordHashFor(String username) throws SQLException {
        initialize();
        try (Connection conn = connect();
             PreparedStatement st = conn.prepareStatement("SELECT password_hash FROM users WHERE username = ?")) {
            st.setString(1, username);
            try (ResultSet rs = st.executeQuery()) { return rs.next() ? rs.getString(1) : null; }
        }
    }

    public static ChatMessage insertMessage(String username, String text) throws SQLException {
        initialize();
        // Insert with the sender determined from the authenticated session, never from the browser payload.
        try (Connection conn = connect();
             PreparedStatement st = conn.prepareStatement(
                "INSERT INTO messages(user_id,content) SELECT id,? FROM users WHERE username=?",
                Statement.RETURN_GENERATED_KEYS)) {
            st.setString(1, text);
            st.setString(2, username);
            if (st.executeUpdate() != 1) throw new SQLException("Authenticated user no longer exists");
            try (ResultSet keys = st.getGeneratedKeys()) {
                if (!keys.next()) throw new SQLException("Message ID was not returned");
                long id = keys.getLong(1);
                return new ChatMessage(id, username, text, Instant.now().toString());
            }
        }
    }

    public static List<ChatMessage> recentMessages() throws SQLException {
        initialize();
        List<ChatMessage> results = new ArrayList<>();
        String sql = "SELECT m.id,u.username,m.content,m.created_at FROM messages m " +
                     "JOIN users u ON u.id=m.user_id ORDER BY m.id DESC LIMIT 100";
        try (Connection conn = connect(); PreparedStatement st = conn.prepareStatement(sql);
             ResultSet rs = st.executeQuery()) {
            while (rs.next()) {
                Timestamp ts = rs.getTimestamp(4);
                results.add(new ChatMessage(rs.getLong(1), rs.getString(2), rs.getString(3),
                        ts.toInstant().toString()));
            }
        }
        Collections.reverse(results);
        return results;
    }
}
